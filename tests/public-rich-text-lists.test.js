import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseFragment,serialize} from 'parse5';
import {marked} from 'marked';
import postcss from 'postcss';
import tailwindcss from 'tailwindcss';
import {transform} from 'esbuild';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
test('actual markdown renderer repairs malformed lists and retains names, nesting and alignment',async()=>{
 const source=read('../src/lib/markdown.ts');
 const {code}=await transform(source,{loader:'ts',format:'esm'});
 const module=await import('data:text/javascript;base64,'+Buffer.from(code.replace(/from "marked"/g,'from '+JSON.stringify(import.meta.resolve('marked'))).replace(/from "parse5"/g,'from '+JSON.stringify(import.meta.resolve('parse5')))).toString('base64'));
 const input='<div style="text-align: justify;"><p>Former Pastors<ol><li>Pastor A (1992)<ul><li>Detail</li></ul></li><li>Pastor B (2002)</li></ol></p><p><ul><li>Other</li></ul></p></div>';
 const html=module.renderMarkdown(input);
 const tree=parseFragment(html);
 const div=tree.childNodes.find(n=>n.tagName==='div');
 assert.equal(div.attrs.find(a=>a.name==='style').value,'text-align: justify;');
 const ol=div.childNodes.find(n=>n.tagName==='ol');
 assert.equal(ol.childNodes.filter(n=>n.tagName==='li').length,2);
 assert.ok(ol.childNodes[0].childNodes.some(n=>n.tagName==='ul'));
 assert.ok(div.childNodes.some(n=>n.tagName==='ul'));
 assert.ok(html.includes('Pastor A (1992)')&&html.includes('Pastor B (2002)'));
 assert.equal(serialize(parseFragment(html)),html);
 assert.ok(!module.renderSafeRichText('<ol><li onclick="evil()">Text<script>evil()</script></li></ol>').includes('evil'));
});
test('Tailwind compiled stylesheet restores scoped list marker declarations',async()=>{
 const css=read('../src/styles/global.css');
 const result=await postcss([tailwindcss({content:[{raw:'<article class="content-page-body"><ol><li>One</li></ol></article><nav><ul><li>Menu</li></ul></nav>'}],corePlugins:{preflight:true}})]).process(css,{from:undefined});
 const rules=new Map();
 result.root.walkRules(rule=>{for(const selector of rule.selectors){const declarations=rules.get(selector)||{};rule.walkDecls(d=>declarations[d.prop]=d.value);rules.set(selector,declarations);}});
 assert.equal(rules.get('.content-page-body ol')['list-style-type'],'decimal');
 assert.equal(rules.get('.content-page-body ul')['list-style-type'],'disc');
 assert.equal(rules.get('.content-page-body ol ol')['list-style-type'],'lower-alpha');
 assert.equal(rules.get('.content-page-body ul ul')['list-style-type'],'circle');
 assert.equal(rules.get('.content-page-body li').display,'list-item');
 assert.equal(rules.get('.content-page-body ol')['padding-inline-start'],'1.8em');
 assert.equal(rules.get('.content-page-body ol')['list-style-position'],'outside');
 assert.ok(!result.css.includes('.content-page-body :global('));
 assert.notEqual(rules.get('ol')?.['list-style-type'],'decimal');
});
